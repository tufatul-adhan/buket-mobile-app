  List<Bouquet> getBuketBerdasarkanKota(String kota) {
    return _bouquets.where((bouquet) => bouquet.city == kota).toList();
  }

  Bouquet? getBuketBerdasarkanId(String id) {
    try {
      return _bouquets.firstWhere((bouquet) => bouquet.id == id);
    } catch (e) {
      return null;
    }
  }

  List<Bouquet> cariBuket(String query) {
    return _bouquets
        .where((bouquet) =>
            bouquet.name.toLowerCase().contains(query.toLowerCase()) ||
            bouquet.description.toLowerCase().contains(query.toLowerCase()))
        .toList();
  }

  List<Bouquet> filterBerdasarkanKategori(String kota, String kategori) {
    return _bouquets
        .where(
            (bouquet) => bouquet.city == kota && bouquet.category == kategori)
        .toList();
  }
